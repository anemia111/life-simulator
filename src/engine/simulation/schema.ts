import { z } from "zod";
import { account } from "../enterprise/schema";
const n = z.number().safe().int().nonnegative(),
  f = z.number().finite().nonnegative(),
  id = z.string().min(1).max(300),
  date = z.string().regex(/^\d{4}-\d{2}-\d{2}$/);
export const simulationSchema = z.object({
  seed: n.max(4294967295),
  randomState: n.max(4294967295),
  residents: z.array(
    z.object({
      ...account,
      id,
      homeId: id,
      motive: z.enum([
        "stability",
        "income",
        "enterprise",
        "spending",
        "saving",
        "mobility",
      ]),
      goal: id,
      standard: z.enum(["frugal", "balanced", "comfortable"]),
      jobId: id.nullable(),
      income: n,
      earned: n,
      consumed: n,
      changes: n,
      lastDecision: id,
      hours: z.object({
        work: f.max(24),
        commute: f.max(24),
        study: f.max(24),
        business: f.max(24),
        essential: f.max(24),
        social: f.max(24),
        care: f.max(24),
        sleep: f.max(24),
        free: f.max(24),
      }),
      contacts: z.array(id).max(30),
      businessId: id.nullable(),
    }),
  ),
  firms: z.array(
    z.object({
      ...account,
      id,
      name: id,
      industry: id,
      ownerId: id,
      founded: date,
      legalForm: z.enum(["company", "sole"]),
      strategy: z.enum(["value", "quality", "growth"]),
      status: z.enum(["active", "closed"]),
      sites: z.array(id),
      employees: z.array(id),
      price: n.min(1),
      quality: f.max(100),
      brand: f,
      wageIndex: f.min(0.5).max(3),
      advertising: n,
      capacity: n,
      lossDays: n,
      creditLimit: n,
      borrowed: n,
      staffHours: f,
      workCarry: f,
      dayOpeningProfit: z.number().safe().int(),
      lastProfit: z.number().safe().int(),
      monthProfit: z.number().safe().int(),
      lastMonthProfit: z.number().safe().int(),
      lastDemand: n,
      lastUnits: n,
      marketShare: f.max(1),
      decisions: n,
    }),
  ),
  districts: z.array(
    z.object({
      id,
      population: n,
      ageShares: z.object({
        young: f.max(1),
        working: f.max(1),
        senior: f.max(1),
      }),
      income: n,
      unemployment: f.max(1),
      rent: f.min(0.1).max(10),
      wage: f.min(0.1).max(10),
      land: f.min(0.1).max(10),
      demand: f.max(10),
    }),
  ),
  markets: z.array(
    z.object({ industry: id, pool: n, allocations: z.record(id, n) }),
  ),
  news: z
    .array(
      z.object({
        id: n,
        date,
        kind: id,
        entityId: id,
        districtId: id.nullable(),
        text: id,
      }),
    )
    .max(120),
  interest: f.max(1),
  unemployment: f.max(1),
  income: n,
  wage: f.max(10),
  rent: f.max(10),
  history: z
    .array(
      z.object({
        date,
        population: n,
        unemployment: f.max(1),
        economy: f,
        price: f,
        income: n,
        firms: n,
      }),
    )
    .max(120),
});
